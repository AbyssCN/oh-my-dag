/**
 * harness/exhaustive —— 判别联合的**穷尽闸**(2026-08-28)。
 *
 * ## 它治的病
 *
 * 判别联合加一格时,消费方分两类:
 *
 * · **读了新格没有的字段** —— `tsc` 当场点名,不用管,它自己会喊。
 * · **只做 `kind === 'x'` 的二值比较** —— **一声不吭**。新格静默落进 `else`,
 *   行为错了而没有任何东西变红。这是加格时唯一一类不会当场红的错。
 *
 * 实账(F2,2026-08-28):给 `AcceptanceSpec` 加第三格 `rubric` 时,前一类三处被 `tsc` 逐个点名、
 * 当场修掉;后一类十来处**全部无声通过**,rubric 一路落进「按探索型处理」那一支。
 * 当时的处置是写一条纪律(逐处定性写进交付说明)—— 而仓规原话是
 * 「加一条纪律之前先问:能不能做成会红的闸?**能 → 写代码,别写在这**」。本模块就是那道闸。
 *
 * ## 用法
 *
 * 在**产值的**穷尽分支末尾调它:
 *
 * ```ts
 * switch (spec.kind) {
 *   case 'executable': return …;
 *   case 'rubric':     return …;
 *   case 'exploratory':return …;
 *   default: return assertNever(spec, `未处理的验收分型: ${JSON.stringify(spec)}`);
 * }
 * ```
 *
 * 少一个 `case`,那一格的类型就不是 `never`,`assertNever` 收不下它 → **编译错误**,
 * 而且逐处点名。
 *
 * ## 它抓不到的那一半(诚实边界)
 *
 * 没有 `else` 的守卫式 `if`(`if (kind === 'x') { …特殊处理… }`)—— 那种加一格照样无声。
 * 那一半的解法不在这里,在**把散落的字面量比较收敛成具名谓词**:让「新增一格该怎么办」
 * 只需要在**一个** switch 里表态,所有调用点继承那次表态(见 `goal/acceptance-shape.ts`)。
 * **两层各管一半,谁也别声称管全了。**
 *
 * ## 为什么运行期也抛
 *
 * 类型系统骗得过,现实骗不过:JSON 反序列化、跨进程边界、旧版本写的账本,
 * 都能送进一个类型系统没见过的值。那时**抛**比静默返回 `undefined` 好 ——
 * 后者会让一个未知分型悄悄变成「什么都没做」,而调用方读到的是成功。
 * 判词里带上那个意外的值(仓规:fail-loud,不吞证据)。
 *
 * @module
 */

/**
 * 穷尽性断言。**只有在类型上确实无剩余成员时才收得下** —— 这正是它的全部价值。
 *
 * @param value 走到这里就是编译期漏了一格(或运行期来了个类型外的值)。
 * @param why   判词,**原样抛出不再措辞**。省略时自动带上那个意外的值。
 */
export function assertNever(value: never, why?: string): never {
  throw new Error(why ?? `assertNever: 未处理的分支 — ${String(value)}`);
}
