/**
 * FanOutQA 喂给引擎的**任务文本**(2026-08-04 冻结)。
 *
 * ## 为什么单独一个文件
 *
 * 交接 21 §八.4 与 §七.5③ 记着一条已经付过学费的账:**改任务文本会让所有历史跑失去可比性**。
 * F2 那行"点名 checklist 文件"的脚注明知该删也没删,就是因为它当时散在任务 md 里、
 * 谁都可以随手改一笔而读数悄悄换了地基。
 *
 * 所以这次把它**放在代码里、只此一份**:结构探针(规划期,不烧语料)与将来的端到端两臂
 * 必须逐字用同一个函数。改这里 = 明知地开一次新基线,git 会记下是谁改的。
 *
 * ## 措辞上的两条刻意
 *
 * 1. **不提"分解/并行/子问题/map"** —— 一旦提示,量到的就是"它听不听话",
 *    而我们要问的是"它自己认不认得出这里该扇出"。
 * 2. **提资料面(维基 2023-11-20 快照)与输出格式** —— 这两条是 FanOutQA 任务本身的一部分
 *    (答案 274/310 是 dict,逐实体一行),不给的话引擎会画一张"格式随缘"的图,
 *    而端到端那一步又得改文本 → 又一次基线断裂。
 */

/** 语料 epoch:FanOutQA 的维基快照日期(README 已核)。写进任务文本,免得引擎按"今天"作答。 */
export const FANOUT_WIKI_EPOCH = '2023-11-20';

/**
 * 一道 FanOutQA 题的任务文本。**结构探针与端到端共用,逐字。**
 */
export function fanoutTaskText(question: string): string {
  return (
    `${question}\n\n` +
    `资料面: 英文维基百科 (${FANOUT_WIKI_EPOCH} 快照)。\n` +
    '产出要求: 一份完整清单, 每个实体一行, 形如 "实体: 值"。不得遗漏任何一个实体, ' +
    '不得用"等等/以此类推"省略。每条值后附它的出处 (维基条目标题)。'
  );
}
