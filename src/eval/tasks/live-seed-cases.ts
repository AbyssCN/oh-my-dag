/**
 * live 冒烟的**带种沙箱**用例 (2026-07-30)。
 *
 * 为什么需要种子: 到目前为止几次 `dag_goal` live 冒烟里, 检测者**无从发挥** —— 目标是"写两份
 * 口径一致的文档", 而两份产出本来就一致 (同一个模型同一轮写的, 上游还常挂着一个共同的决策节点)。
 * 于是"标了 detector 之后环是不是真的更好收敛"这个问题, 现成的冒烟一次都没真正问出口:
 * 检测者跑了、协议也通了, 但它从来没有**抓到过东西**, 因此也从来没有机会改变环的走向。
 *
 * 造一次真冲突有两条路, 这里选第二条:
 *   ① 让两个写方独立起草、禁止共同的事实节点 —— 那是**逼图画错**再看闸响不响, 测的是稻草人
 *      (one-decision-then-fanout 恰恰是这种活的正解, 图那么画本来就该扣分)。
 *   ② **把矛盾放进源材料**: 沙箱里两份既有文件对同一个事实各说一套。图怎么画都对, 而两个
 *      分头读材料的节点必然产出对不上的结论 —— 冲突是**输入**给的, 不是图的错。
 *
 * ②同时问出了第二个没有读数的问题: 这种冲突**再跑多少轮都推不动** (材料就是矛盾的, 得有人
 * 拍板), 所以正确的出口是 `BLOCKED:` 而不是 `REJECT:` 循环重跑。BLOCKED 那条异步出口至今
 * 只有注入式测试, live 一次没走过。
 */

export interface LiveSeedCase {
  id: string;
  /** 种进沙箱的既有文件 (相对路径 → 内容)。 */
  files: Record<string, string>;
  /** 喂给 `dag_goal` 的目标。 */
  goal: string;
  /** 这次冒烟要看的那一位信息 —— 写下来免得跑完拿别的读数凑答案。 */
  watchFor: string;
}

