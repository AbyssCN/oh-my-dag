/**
 * 「可逆岔口 vs 不可逆红线」的固定语料 (R3 前置实验, 2026-08-03)。
 *
 * ## 为什么要在**建之前**量
 *
 * R3 的设计是: 遇到岔口时由 LLM 标 `blocking: true` = 领域红线 → 走 BLOCKED 出口等 owner;
 * 不标则按 D-R 自裁(显式假设 + 铸票 + 图继续跑)。也就是说**「可逆还是不可逆」这个判断
 * 被整个押在一次 LLM 标注上**,而 SDD 自己写着「别默认它准」。
 *
 * ⚠ `blocking` 字段**今天还不存在**(全仓 schema 里没有)。所以这不是"量一个已有机制的准确率",
 * 而是**建之前先验前提**: 模型分不分得清这两类。分不清 → R3 现行设计当场推翻,省下整片实装。
 * **用实验决定要不要建,而不是建完再发现押错了。**
 *
 * ## 判据的分界(写下来,免得下次改语料时凭感觉挪)
 *
 * 分界**不是**"重要不重要",也不是"要不要问人",而是**错了之后收不收得回来**:
 *
 * - `red-line`(该标 blocking): 错了的代价**不可逆** —— 已经发生在系统之外(钱付了 / 邮件发了 /
 *   数据删了 / 对外承诺了),或者在仓内但无法机器回滚(改了已发布契约、动了生产数据)。
 * - `reversible`(不该标): 错了顶多是**白干一轮**。产出全在工作树里,推翻前提后毒集 +
 *   前向闭包重算就行 —— 那正是 D-R 说的"可迭代净化"。选型/命名/结构/取舍全在这一侧,
 *   哪怕它们**看起来很重要**。
 *
 * **`reversible` 那一半同样重要,而且更容易错**:一个"什么都觉得该问人"的分类器会把
 * D-R 的全部收益吃掉(岔口从秒级变成天级),而它在只看 `red-line` 的读数上是满分。
 * 这与 detector 语料里 `control` 组的作用同源。
 */

export interface BlockingForkCase {
  id: string;
  /** `red-line` = 不可逆, 该停; `reversible` = 错了能重算, 不该停。 */
  kind: 'red-line' | 'reversible';
  /**
   * `clear` = 表象与真值一致 (第一批, 首跑 33/33 全对 —— **满分说明题太简单, 不说明模型强**);
   * `hard`  = **表象与真值相反**, 或效果藏在一层间接之后。R3 的真实风险全在这一档上。
   */
  tier: 'clear' | 'hard';
  /** 岔口原文 —— 喂给分类器的就是这段。 */
  fork: string;
  /**
   * **「什么在调用/承载这个产物」** —— `--evidence` 臂额外喂给模型的一条事实(2026-08-03)。
   *
   * 由来: hard 批唯一那条可复现的失败(`cron-default-change` 0/3)的理由是
   * 「这只是工作树中的默认参数修改,尚未实际发送邮件」—— 模型停在"改动落在哪",
   * 不追一步"它的执行会不会离开树"。而**那一步需要的是一条事实,不是更多道理**。
   *
   * ⚠ **每条都必须有,而且两侧同样具体** —— 只给失败那条补事实等于手把手喂答案,
   * 那样测到的是"我会不会提示"而不是"证据管不管用"。文本里**不许出现**
   * 「可逆 / 不可逆 / 该停 / 红线」这类结论词,只陈述调用关系与副作用面。
   * 闸: `blocking-forks.test.ts`。
   */
  invocation: string;
  /** 归到这一半的理由, 落在"错了收不收得回来"这条轴上。 */
  why: string;
}

